"use client";

import { Button } from "@/components/ui/button";
import { Popover, PopoverContent, PopoverTrigger } from "@/components/ui/popover";
import { api, type Meta } from "@/lib/api";
import { cn } from "@/lib/utils";
import { useAsync } from "@/lib/useAsync";
import { Icon } from "./icons";

/** Header chip with the answer mode; opens the versions and retrieval settings behind answers. */
export function SystemInfo() {
  const { data: meta, error } = useAsync<Meta>(() => api.meta(), []);
  const label = error
    ? "API unreachable"
    : !meta
      ? "Connecting"
      : meta.llm.enabled
        ? meta.llm.model
        : "System";

  return (
    <Popover>
      <PopoverTrigger asChild>
        <Button
          variant="outline"
          className="h-8 gap-2 bg-card px-2.5 font-normal text-foreground/80 shadow-card"
          title={meta && !meta.llm.enabled ? "Answer settings and versions" : undefined}
        >
          <span
            className={cn(
              "size-2 shrink-0 rounded-full",
              error ? "bg-destructive" : !meta ? "bg-muted-foreground/40" : "bg-success",
            )}
          />
          <span className="hidden sm:inline">{label}</span>
          <Icon name="chevronDown" className="hidden size-3 text-muted-foreground sm:block" />
        </Button>
      </PopoverTrigger>
      <PopoverContent align="end" className="w-[22rem] p-1.5">
        <div className="px-3 pt-2.5 pb-2">
          <p className="eyebrow">System</p>
          <p className="mt-1 text-[13px] leading-snug text-muted-foreground">
            {error
              ? "The API is unreachable."
              : !meta
                ? "Loading…"
                : meta.llm.enabled
                  ? "Answers are generated by the LLM, grounded in retrieved sources."
                  : "Answers quote the most relevant evidence with citations. Add an Anthropic API key to generate written answers."}
          </p>
        </div>
        {meta && (
          <dl className="divide-y rounded-md border bg-muted/40 text-[13px]">
            <Row label="LLM">
              {meta.llm.enabled
                ? `${meta.llm.model}${meta.llm.effort ? ` · effort ${meta.llm.effort}` : ""}`
                : "not configured"}
            </Row>
            <Row label="Prompt">{meta.prompt_version}</Row>
            <Row label="Embeddings">{meta.embedding_model}</Row>
            <Row label="Reranker">{meta.reranker_model ?? "—"}</Row>
            <Row label="Retrieval">
              {meta.retrieval.mode} · k {meta.retrieval.k} · {meta.retrieval.candidates} cand.
            </Row>
            <Row label="RRF k">{meta.retrieval.rrf_k}</Row>
            <Row label="Min rerank">{meta.retrieval.min_rerank_score ?? "—"}</Row>
            <Row label="Index">{meta.index.current_chunks} chunks</Row>
          </dl>
        )}
      </PopoverContent>
    </Popover>
  );
}

function Row({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="grid grid-cols-[6.5rem_1fr] gap-3 px-3 py-2">
      <dt className="text-muted-foreground">{label}</dt>
      <dd className="font-mono text-[11.5px] leading-5 break-all">{children}</dd>
    </div>
  );
}
