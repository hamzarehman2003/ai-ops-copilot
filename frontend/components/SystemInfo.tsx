"use client";

import { useEffect, useRef, useState } from "react";
import { api, type Meta } from "@/lib/api";
import { useAsync } from "@/lib/useAsync";
import { Icon } from "./icons";
import { cx } from "./ui";

/** Small "System" popover: LLM mode, prompt/model versions, retrieval params, index size. */
export function SystemInfo() {
  const { data: meta, error } = useAsync<Meta>(() => api.meta(), []);
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!open) return;
    const onClick = (e: MouseEvent) => {
      if (ref.current && !ref.current.contains(e.target as Node)) setOpen(false);
    };
    document.addEventListener("mousedown", onClick);
    return () => document.removeEventListener("mousedown", onClick);
  }, [open]);

  const state = error ? "API unreachable" : !meta ? "Connecting" : meta.llm.enabled ? "LLM" : "Offline";

  return (
    <div className="relative" ref={ref}>
      <button
        type="button"
        onClick={() => setOpen((o) => !o)}
        className="flex h-8 items-center gap-2 rounded-lg border border-line bg-surface px-2.5 text-[12.5px] text-ink-2 transition-colors hover:border-line-strong"
        aria-expanded={open}
        title={meta && !meta.llm.enabled ? "No LLM key configured: answers are extractive" : undefined}
      >
        <span className="relative flex h-2 w-2">
          {meta && (
            <span
              className={cx(
                "absolute inline-flex h-full w-full animate-ping rounded-full opacity-40",
                meta.llm.enabled ? "bg-ok" : "bg-warn",
              )}
            />
          )}
          <span
            className={cx(
              "relative inline-flex h-2 w-2 rounded-full",
              error ? "bg-bad" : !meta ? "bg-ink-4" : meta.llm.enabled ? "bg-ok" : "bg-warn",
            )}
          />
        </span>
        <span className="hidden font-medium whitespace-nowrap sm:inline">
          {state === "Offline" ? "Offline mode" : state === "LLM" ? meta?.llm.model : state}
        </span>
        <Icon name="chevronDown" className="hidden h-3 w-3 text-ink-4 sm:block" />
      </button>
      {open && (
        <div className="absolute right-0 z-40 mt-2 w-[22rem] animate-rise rounded-xl border border-line bg-surface p-1.5 shadow-pop">
          <div className="px-3 pt-2.5 pb-2">
            <div className="eyebrow">System</div>
            <p className="mt-1 text-[12.5px] leading-snug text-ink-3">
              {error
                ? "The API is unreachable."
                : !meta
                  ? "Loading…"
                  : meta.llm.enabled
                    ? "Answers are generated by the LLM, grounded in retrieved sources."
                    : "No LLM key configured: answers quote the retrieved evidence instead of generating text."}
            </p>
          </div>
          {meta && (
            <dl className="divide-y divide-line rounded-lg border border-line bg-paper/60 text-[12.5px]">
              <Row label="LLM">
                {meta.llm.enabled
                  ? `${meta.llm.model}${meta.llm.effort ? ` · effort ${meta.llm.effort}` : ""}`
                  : "offline"}
              </Row>
              <Row label="Prompt">{meta.prompt_version}</Row>
              <Row label="Embeddings">{meta.embedding_model}</Row>
              <Row label="Reranker">{meta.reranker_model ?? "—"}</Row>
              <Row label="Retrieval">
                {meta.retrieval.mode} · k {meta.retrieval.k} · {meta.retrieval.candidates} cand.
              </Row>
              <Row label="RRF k">{meta.retrieval.rrf_k}</Row>
              <Row label="Min rerank">{meta.retrieval.min_rerank_score ?? "—"}</Row>
              <Row label="Index">{meta.index.current_chunks} chunks</Row>
            </dl>
          )}
        </div>
      )}
    </div>
  );
}

function Row({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="grid grid-cols-[6.5rem_1fr] gap-3 px-3 py-2">
      <dt className="text-ink-3">{label}</dt>
      <dd className="font-mono text-[11.5px] leading-5 break-all text-ink">{children}</dd>
    </div>
  );
}
